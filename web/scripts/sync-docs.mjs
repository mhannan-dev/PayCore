// Generates web/src/content/user-guide.ts from the canonical docs/user_guide.md,
// so the /docs page bundles the guide at build time: no runtime file reads, and
// the Docker build (context web/) uses the committed generated module.
// When docs/ is absent (e.g. inside the Docker build) the committed file is kept.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";

const source = new URL("../../docs/user_guide.md", import.meta.url);
const target = new URL("../src/content/user-guide.ts", import.meta.url);

if (existsSync(source)) {
  const markdown = readFileSync(source, "utf8");
  const next = "// GENERATED by web/scripts/sync-docs.mjs from docs/user_guide.md. Do not edit; edit the Markdown.\n"
    + `export const USER_GUIDE_MARKDOWN: string = ${JSON.stringify(markdown)};\n`;
  mkdirSync(new URL("../src/content/", import.meta.url), { recursive: true });
  if (!existsSync(target) || readFileSync(target, "utf8") !== next) writeFileSync(target, next);
  console.log("docs: synced docs/user_guide.md → web/src/content/user-guide.ts");
} else {
  console.log("docs: docs/user_guide.md not found; using the committed web/src/content/user-guide.ts");
}
